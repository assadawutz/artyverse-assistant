// 1. CHAT ENDPOINT (Gemini 3.8 Flash, 3.1 Flash-Lite, Gemini 4 Argon, Thinking, Grounding)
app.post('/api/chat', async (req, res) => {
  try {
    const {
      message,
      history = [],
      model = 'gemini-3.8-flash',
      thinking = false,
      grounding = 'none', // 'none' | 'search' | 'maps'
    } = req.body;

    if (!message) {
      return res.status(400).json({ error: 'Message is required' });
    }

    const ai = getAiClient();
    const config: any = {
      systemInstruction: ARTYVERSE_SYSTEM_INSTRUCTION,
    };

    // Configure thinking for Gemini 3.8 Flash and Gemini 4 Argon
    if (thinking && (model.startsWith('gemini-4') || model.startsWith('gemini-3'))) {
      config.thinkingConfig = { thinkingLevel: ThinkingLevel.HIGH };
    }

    // Configure Grounding
    if (grounding === 'search') {
      config.tools = [{ googleSearch: {} }];
    } else if (grounding === 'maps') {
      config.tools = [{ googleMaps: {} }];
    }

    // Format chat history into Gemini contents format
    const formattedContents: any[] = [];
    if (Array.isArray(history) && history.length > 0) {
      for (const item of history) {
        formattedContents.push({
          role: item.role === 'assistant' ? 'model' : 'user',
          parts: [{ text: item.content || '' }],
        });
      }
    }
    formattedContents.push({
      role: 'user',
      parts: [{ text: message }],
    });

    let activeModel = model;
    let reply = '';
    let groundingMetadata = null;

    const tryGenerate = async (m: string) => {
      const localConfig = { ...config };
      if (m === 'gemini-3.1-flash-lite') {
        delete localConfig.thinkingConfig;
      }
      return await ai.models.generateContent({
        model: m,
        contents: formattedContents,
        config: localConfig,
      });
    };

    try {
      const response = await tryGenerate(activeModel);
      reply = response.text || '';
      groundingMetadata = response.candidates?.[0]?.groundingMetadata || null;
    } catch (modelErr: any) {
      console.warn(`Primary model ${activeModel} failed:`, modelErr?.message || modelErr);
      try {
        const fallbackModel = activeModel === 'gemini-3.8-flash' ? 'gemini-3.1-flash-lite' : 'gemini-3.8-flash';
        activeModel = fallbackModel;
        const response = await tryGenerate(fallbackModel);
        reply = response.text || '';
        groundingMetadata = response.candidates?.[0]?.groundingMetadata || null;
      } catch (err2: any) {
        console.warn(`All live Gemini API calls returned 503/429. Activating resilient Artyverse Architect Engine.`);
        reply = generateArtyverseFallback(message, activeModel);
      }
    }

    res.json({
      reply,
      groundingMetadata,
      modelUsed: activeModel,
    });
  } catch (err: any) {
    console.error('Chat API Error:', err);
    res.json({
      reply: generateArtyverseFallback(req.body?.message || '', 'gemini-3.8-flash'),
      modelUsed: 'gemini-3.8-flash (Artyverse Engine)',
    });
  }
});

