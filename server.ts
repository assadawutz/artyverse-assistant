// 7. MUSIC GENERATION - LYRIA (lyria-3-clip-preview / lyria-3-pro-preview)
app.post('/api/generate-music', async (req, res) => {
  try {
    const {
      prompt = 'Calm, gentle, uplifting Thai-inspired acoustic melody for elderly meditation and peaceful mobile UX.',
      model = 'lyria-3-clip-preview',
    } = req.body;

    const ai = getAiClient();
    const responseStream = await ai.models.generateContentStream({
      model: model || 'lyria-3-clip-preview',
      contents: prompt,
    });

    let audioBase64 = '';
    let lyrics = '';
    let mimeType = 'audio/wav';

    for await (const chunk of responseStream) {
      const parts = chunk.candidates?.[0]?.content?.parts;
      if (!parts) continue;
      for (const part of parts) {
        if (part.inlineData?.data) {
          if (!audioBase64 && part.inlineData.mimeType) {
            mimeType = part.inlineData.mimeType;
          }
          audioBase64 += part.inlineData.data;
        }
        if (part.text && !lyrics) {
          lyrics = part.text;
        }
      }
    }

    if (!audioBase64) {
      return res.status(500).json({ error: 'No audio generated by Lyria' });
    }

    res.json({
      audioUrl: `data:${mimeType};base64,${audioBase64}`,
      lyrics,
      mimeType,
    });
  } catch (err: any) {
    console.error('Music generation error:', err);
    res.status(500).json({ error: err.message || 'Music generation failed' });
  }
});

