// 5. IMAGE GENERATION & EDITING (Gemini Nano Banana 2.1 / Pro Image / Flash Lite Image)
app.post('/api/image-gen', async (req, res) => {
  try {
    const {
      prompt,
      aspectRatio = '1:1', // "1:1", "2:3", "3:2", "3:4", "4:3", "9:16", "16:9", "21:9"
      imageSize = '1K',    // "1K", "2K", "4K"
      model = 'gemini-nano-banana-2.1',
      baseImage = null,
      mimeType = 'image/png',
    } = req.body;

    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const ai = getAiClient();
    const parts: any[] = [];

    if (baseImage) {
      const cleanImg = baseImage.replace(/^data:image\/[a-zA-Z0-9+.-]+;base64,/, '');
      parts.push({
        inlineData: {
          mimeType,
          data: cleanImg,
        },
      });
    }

    parts.push({ text: prompt });

    const config: any = {};
    if (!baseImage) {
      // Configuration for generating new images
      config.imageConfig = {
        aspectRatio: aspectRatio || '1:1',
      };
      if (model === 'gemini-nano-banana-2.1' || model === 'gemini-3-pro-image') {
        config.imageConfig.imageSize = imageSize || '1K';
      }
    }

    const response = await ai.models.generateContent({
      model: model || 'gemini-nano-banana-2.1',
      contents: { parts },
      config,
    });

    let imageUrl: string | null = null;
    let descriptionText = '';

    const candidateParts = response.candidates?.[0]?.content?.parts || [];
    for (const part of candidateParts) {
      if (part.inlineData) {
        imageUrl = `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
      } else if (part.text) {
        descriptionText += part.text + ' ';
      }
    }

    if (!imageUrl) {
      return res.status(500).json({
        error: 'No image data returned from model',
        text: descriptionText,
      });
    }

    res.json({
      imageUrl,
      text: descriptionText.trim(),
    });
  } catch (err: any) {
    console.error('Image gen error:', err);
    res.status(500).json({ error: err.message || 'Image generation failed' });
  }
});

